#!/bin/bash
# ---------------------------------------------------------------------------
# config.sh — view and edit the configuration.
#
#   sudo ./config.sh                 interactive editor (TUI)
#   ./config.sh --show               print the effective configuration
#   ./config.sh --detect             fill values from the running system
#   ./config.sh --set KEY=VALUE      set one value (scriptable)
#   ./config.sh --unset KEY          drop one override
#   ./config.sh --reset              delete all overrides
#
# Edits are written to scripts/00-config.local.sh, which is gitignored and
# sourced *after* 00-config.sh, so your settings survive `git pull`.
# Every value is validated before it is accepted.
# ---------------------------------------------------------------------------
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
. "$HERE/lib/common.sh"
# shellcheck source=00-config.sh
. "$HERE/00-config.sh"

set -u
LOCAL="$HERE/00-config.local.sh"

# ---- managed keys ----------------------------------------------------------
KEYS=(PI_HOSTNAME PI_IP PI_CIDR PI_GATEWAY PI_DNS NIC BRIDGE PI_SUBNET WORKDIR PVE_PACKAGES PVE_TEMPLATES)
declare -A DESC=(
  [PI_HOSTNAME]="Hostname of the Pi (must match \`hostname\`)"
  [PI_IP]="Static IP for the Pi / the Proxmox bridge"
  [PI_CIDR]="Network prefix length (e.g. 24)"
  [PI_GATEWAY]="Router / default gateway"
  [PI_DNS]="DNS resolvers (space-separated)"
  [NIC]="Physical wired interface to enslave"
  [BRIDGE]="Proxmox bridge name"
  [PI_SUBNET]="LAN subnet to advertise over Tailscale"
  [WORKDIR]="Where backups/logs/helpers live on the Pi"
  [PVE_PACKAGES]="Proxmox packages to install"
  [PVE_TEMPLATES]="arm64 LXC templates to pre-download"
)

# ---- validators ------------------------------------------------------------
is_ipv4() {
  local ip="$1"
  [[ "$ip" =~ ^([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})$ ]] || return 1
  local o
  for o in "${BASH_REMATCH[@]:1}"; do [ "$o" -le 255 ] || return 1; done
  return 0
}
is_cidr() { # a.b.c.d/nn
  local c="$1" ip="${1%%/*}" plen="${1##*/}"
  [ "$c" != "$plen" ] || return 1
  is_ipv4 "$ip" || return 1
  [[ "$plen" =~ ^[0-9]{1,2}$ ]] || return 1
  [ "$plen" -ge 1 ] && [ "$plen" -le 32 ] || return 1
  return 0
}
is_ifname() { [[ "$1" =~ ^[A-Za-z0-9_.:@-]{1,15}$ ]]; }

validate() { # validate <KEY> <VALUE>  -> 0 ok, prints reason on failure
  local k="$1" v="$2"
  [ -n "$v" ] || { printf 'value must not be empty'; return 1; }
  case "$k" in
    PI_IP|PI_GATEWAY) is_ipv4 "$v" || { printf 'not a valid IPv4 address'; return 1; } ;;
    PI_CIDR) [[ "$v" =~ ^[0-9]{1,2}$ ]] && [ "$v" -ge 1 ] && [ "$v" -le 32 ] || { printf 'must be 1-32'; return 1; } ;;
    PI_DNS)
      local d
      for d in $v; do is_ipv4 "$d" || { printf "'%s' is not a valid IPv4 address" "$d"; return 1; }; done ;;
    PI_SUBNET) is_cidr "$v" || { printf 'not a valid CIDR (e.g. 192.168.0.0/24)'; return 1; } ;;
    NIC|BRIDGE) is_ifname "$v" || { printf 'not a valid interface name'; return 1; } ;;
    PI_HOSTNAME) [[ "$v" =~ ^[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?$ ]] || { printf 'not a valid hostname'; return 1; } ;;
    WORKDIR) [[ "$v" = /* ]] || { printf 'must be an absolute path'; return 1; } ;;
    *) : ;;
  esac
  return 0
}

value_of() { local v; eval "v=\${$1-}"; printf '%s' "$v"; }
is_overridden() { [ -f "$LOCAL" ] && grep -qE "^$1=" "$LOCAL" 2>/dev/null; }

# Read the built-in default for a key straight out of 00-config.sh
# (lines look like:  : "${PI_IP:=192.168.0.15}" ).
builtin_default() {
  awk -v k="$1" '
    index($0, ": \"${" k ":=") == 1 {
      s = $0
      sub(/^: "\$\{[^:]+:=/, "", s)
      sub(/\}"$/, "", s)
      print s; exit
    }' "$HERE/00-config.sh"
}

# ---- persistence -----------------------------------------------------------
# Only keys that differ from the built-in defaults are written, so the file
# stays a minimal diff and survives upstream default changes cleanly.
save_overrides() {
  local tmp k v d wrote=0
  tmp=$(mktemp) || die "cannot create temp file"
  {
    printf '# Local overrides for proxmox-dietpi-rpi4 — generated by config.sh\n'
    printf '# Gitignored. Sourced after 00-config.sh, so these values win.\n'
    printf '# Delete this file (or run: ./config.sh --reset) to return to defaults.\n\n'
    for k in "${KEYS[@]}"; do
      v=$(value_of "$k")
      d=$(builtin_default "$k")
      if [ "$v" != "$d" ]; then
        printf '%s=%q\n' "$k" "$v"
        wrote=1
      fi
    done
  } > "$tmp"
  if [ "$wrote" = 1 ]; then
    mv -f "$tmp" "$LOCAL"
    chmod 600 "$LOCAL" 2>/dev/null || true
  else
    rm -f "$tmp" "$LOCAL"
  fi
}

unset_override() {
  [ -f "$LOCAL" ] || return 0
  local tmp; tmp=$(mktemp) || return 1
  grep -vE "^$1=" "$LOCAL" > "$tmp" && mv -f "$tmp" "$LOCAL"
}

set_and_save() { # set_and_save <KEY> <VALUE>
  local k="$1" v="$2" reason
  if ! reason=$(validate "$k" "$v"); then
    err "$k: $reason"; return 1
  fi
  printf -v "$k" '%s' "$v"          # no eval: safe with spaces/specials
  save_overrides
  ok "$k = $(value_of "$k")   (saved to 00-config.local.sh)"
  return 0
}

# ---- detection -------------------------------------------------------------
detect() {
  say "Detecting values from this system"
  local dev ip cidr gw dns
  dev=$(ip route show default 2>/dev/null | awk '/default/{print $5; exit}')
  # if the default route is on a bridge, find the physical port beneath it
  local nic="$dev"
  if [ -n "$dev" ] && [ -d "/sys/class/net/$dev/bridge" ]; then
    local port
    port=$(ls /sys/class/net/"$dev"/brif 2>/dev/null | head -1)
    [ -n "$port" ] && nic="$port"
  fi
  ip=$(hostname -I 2>/dev/null | awk '{print $1}')
  cidr=$(ip -o -f inet addr show "${dev:-$nic}" 2>/dev/null | awk '{print $4}' | head -1)
  gw=$(ip route show default 2>/dev/null | awk '/default/{print $3; exit}')
  dns=$(awk '/^nameserver/{printf "%s ", $2}' /etc/resolv.conf 2>/dev/null | sed 's/ $//')

  [ -n "$nic" ] && [ "$(value_of NIC)" != "$nic" ] && { NIC="$nic"; step "NIC      = $nic"; }
  [ -n "$ip" ]  && { PI_IP="$ip";  step "PI_IP    = $ip"; }
  [ -n "$cidr" ] && { PI_CIDR="${cidr##*/}"; step "PI_CIDR  = ${cidr##*/}"; }
  [ -n "$gw" ]  && { PI_GATEWAY="$gw"; step "PI_GATEWAY = $gw"; }
  [ -n "$dns" ] && case "$dns" in 127.*) : ;; *) PI_DNS="$dns"; step "PI_DNS   = $dns" ;; esac
  if [ -n "$ip" ] && [ -n "$cidr" ]; then
    local net
    net=$(python3 -c "import ipaddress,sys;print(ipaddress.ip_network('$ip/${cidr##*/}',strict=False))" 2>/dev/null)
    [ -n "$net" ] && { PI_SUBNET="$net"; step "PI_SUBNET = $net"; }
  fi
  local hn; hn=$(hostname)
  [ -n "$hn" ] && { PI_HOSTNAME="$hn"; step "PI_HOSTNAME = $hn"; }
  if bridge_exists "${BRIDGE:-vmbr0}" 2>/dev/null || [ -d /sys/class/net/vmbr0 ]; then
    step "BRIDGE   = ${BRIDGE:-vmbr0} (existing bridge kept)"
  fi
  save_overrides
  ok "saved detected values"
}

# ---- display ---------------------------------------------------------------
show_all() {
  printf '\n%sEffective configuration%s  (%s)\n' "$C_BOLD$C_CYAN" "$C_RESET" \
    "$( [ -f "$LOCAL" ] && echo "with overrides from 00-config.local.sh" || echo "built-in defaults" )"
  hr
  local k mark v
  for k in "${KEYS[@]}"; do
    mark=" "; is_overridden "$k" && mark="*"
    printf '  %s%s %-15s%s %s\n' "$C_DIM" "$mark" "$k" "$C_RESET" "$(value_of "$k")"
  done
  hr
  printf '  %s* = overridden in 00-config.local.sh%s\n' "$C_DIM" "$C_RESET"
  printf '  %s\n\n' "${DESC[PI_IP]}"
}

# ---- interactive editor ----------------------------------------------------
prompt_value() { # prompt_value <KEY>
  local k="$1" cur new reason
  cur=$(value_of "$k")
  printf '\n%s%s%s\n  %s\n' "$C_BOLD$C_CYAN" "$k" "$C_RESET" "${DESC[$k]}"
  printf '  current: %s%s%s\n' "$C_YELLOW" "$cur" "$C_RESET"
  read -r -p "  new value (Enter = keep, '-' = clear): " new || return 1
  case "$new" in
    '') info "kept '$cur'"; return 0 ;;
    '-') unset "$k" 2>/dev/null || true
         unset_override "$k"
         # shellcheck source=/dev/null
         . "$HERE/00-config.sh"
         ok "$k override removed — back to the default ($(value_of "$k"))"
         return 0 ;;
  esac
  if ! reason=$(validate "$k" "$new"); then
    err "$k: $reason — not saved"; return 1
  fi
  case "$k" in
    NIC) [ -d "/sys/class/net/$new" ] || warn "'$new' is not present on this machine right now (fine if you are re-imaging)" ;;
    PI_SUBNET) warn "remember to approve this route in the Tailscale admin console if you use the subnet router" ;;
  esac
  confirm_yes "Save $k = $new ?" && set_and_save "$k" "$new" || info "not saved"
}

editor() {
  local n=${#KEYS[@]} i k
  while :; do
    local header
    header=$(
      printf '  %sEdit configuration%s\n' "$C_BOLD$C_CYAN" "$C_RESET"
      printf '  %sValues marked * are overridden in 00-config.local.sh%s\n' "$C_DIM" "$C_RESET"
      hr
      for k in "${KEYS[@]}"; do
        printf '  %s%-15s%s %s\n' "$C_DIM" "$k" "$C_RESET" "$(value_of "$k")"
      done
      hr
    )
    local -a opts=()
    for k in "${KEYS[@]}"; do
      if is_overridden "$k"; then opts+=("* $k"); else opts+=("  $k"); fi
    done
    opts+=( "Autodetect from this system" "Re-run preflight checks" "Reset ALL values to defaults" "Back" )

    if tui_menu "$header" "${opts[@]}"; then
      local c=$TUI_CHOICE
      if [ "$c" -le "$n" ]; then
        prompt_value "${KEYS[$((c-1))]}"
        pause_tty
      elif [ "$c" -eq $((n+1)) ]; then
        detect; pause_tty
      elif [ "$c" -eq $((n+2)) ]; then
        "$HERE/preflight.sh" || true; pause_tty
      elif [ "$c" -eq $((n+3)) ]; then
        if confirm_yes "Delete 00-config.local.sh and return to built-in defaults?"; then
          rm -f "$LOCAL"
          local kk
          for kk in "${KEYS[@]}"; do unset "$kk" 2>/dev/null || true; done
          # shellcheck source=/dev/null
          . "$HERE/00-config.sh"
          ok "overrides deleted — back to built-in defaults"
        fi
        pause_tty
      else
        return 0
      fi
      [ -t 0 ] && clear 2>/dev/null || true
    else
      return 0
    fi
  done
}

pause_tty() {
  [ -t 0 ] || return 0
  printf '\n%sPress Enter to continue…%s' "$C_DIM" "$C_RESET"
  read -r _ || true
}

# ---- CLI -------------------------------------------------------------------
case "${1:-}" in
  --show|-s)   show_all ;;
  --detect|-d) detect; show_all ;;
  --reset)     rm -f "$LOCAL"; ok "all overrides deleted (back to built-in defaults)"; show_all ;;
  --set)
    [ -n "${2:-}" ] || die "usage: $0 --set KEY=VALUE"
    k="${2%%=*}"; v="${2#*=}"
    [ "$k" != "$2" ] || die "usage: $0 --set KEY=VALUE"
    set_and_save "$k" "$v" || exit 1 ;;
  --unset)
    [ -n "${2:-}" ] || die "usage: $0 --unset KEY"
    unset_override "$2"; ok "$2 override removed" ;;
  --help|-h)
    sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//' ;;
  '') editor ;;
  *) die "unknown option '$1' (try --help)" ;;
esac
