#!/bin/bash
# ---------------------------------------------------------------------------
# 02-network.sh — Stage 2
#
#  * write the authoritative /etc/network/interfaces (eth0 -> vmbr0 bridge)
#  * retire DietPi's /etc/network/interfaces.d/ drop-in
#  * arm the one-shot rollback guard
#  * reboot
#
# After the reboot, reconnect and run 03-install-proxmox.sh.
# ---------------------------------------------------------------------------
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=00-config.sh
. "$HERE/00-config.sh"

say() { printf '\n==> %s\n' "$*"; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || die "run as root (sudo $0)"
[ -f "$WORKDIR/backup/interfaces" ] || die "run 01-prepare.sh first (no backup found in $WORKDIR/backup)"

say "Write /etc/network/interfaces"
cat > /etc/network/interfaces <<EOF
# /etc/network/interfaces -- Proxmox VE bridge layout
# Generated by proxmox-dietpi-rpi4 on $(date -Is)
# Original DietPi configuration backed up in $WORKDIR/backup/

auto lo
iface lo inet loopback

# Physical NIC: no IP of its own, enslaved to the bridge
auto $NIC
iface $NIC inet manual

# Proxmox management bridge
auto $BRIDGE
iface $BRIDGE inet static
        address $PI_IP/$PI_CIDR
        gateway $PI_GATEWAY
        dns-nameservers $PI_DNS
        bridge-ports $NIC
        bridge-stp off
        bridge-fd 0
EOF
cat /etc/network/interfaces

say "Retire DietPi's drop-in"
mkdir -p "$WORKDIR/disabled"
[ -f /etc/network/interfaces.d/eth0.conf ] && mv /etc/network/interfaces.d/eth0.conf "$WORKDIR/disabled/eth0.conf" || true
rm -f /etc/network/interfaces.d/*

say "Read-only parse check"
ifquery -a || true

say "Arm the boot rollback guard"
sed "s|__GATEWAY__|$PI_GATEWAY|g" "$HERE/net-guard.sh" > "$WORKDIR/net-guard.sh"
install -m 755 "$WORKDIR/net-guard.sh" /usr/local/sbin/net-guard.sh
cat > /etc/systemd/system/net-guard.service <<'UNIT'
[Unit]
Description=Network rollback guard (reverts a broken bridge config once)
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
ExecStart=/usr/local/sbin/net-guard.sh
TimeoutStartSec=300

[Install]
WantedBy=multi-user.target
UNIT
systemctl daemon-reload
systemctl enable net-guard.service
rm -f /var/lib/.net-guard-ran
echo "  guard enabled: $(systemctl is-enabled net-guard.service)"

say "Rebooting"
sync
sleep 2
systemctl reboot
