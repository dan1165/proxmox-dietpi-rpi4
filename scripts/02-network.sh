#!/bin/bash
# ---------------------------------------------------------------------------
# 02-network.sh — Stage 2 (gated): rebuild networking around a bridge.
#
# This is the one step that can lock you out, so it is guarded three ways:
#   gate 1  preflight checks
#   gate 2  you type APPLY-NETWORK, then an abortable countdown
#   gate 3  the config is validated + the rollback guard is proven armed
#           BEFORE rebooting; stage 3 re-verifies the live network afterwards.
# ---------------------------------------------------------------------------
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
. "$HERE/lib/common.sh"
# shellcheck source=00-config.sh
. "$HERE/00-config.sh"

WORKDIR="${WORKDIR:-/root/proxmox-setup}"
mkdir -p "$WORKDIR"
LOG_FILE="$WORKDIR/02-network.log"
install_error_trap "02-network"
require_root
require_tty_or_yes
acquire_lock

# ---- gate 1 ---------------------------------------------------------------
gate_preflight "$HERE" || exit 1
[ -f "$WORKDIR/backup/interfaces" ] || die "no backup found — run 01-prepare.sh first"

# ---- gate 2 ---------------------------------------------------------------
cat <<EOF

  ${C_BOLD}About to replace networking.${C_RESET}

  ${NIC}          will become a plain uplink (no IP)
  ${BRIDGE}       will take over $PI_IP/$PI_CIDR, gateway $PI_GATEWAY

  After this the box reboots. If the bridge fails to come up, the rollback
  guard reverts the config and reboots once, restoring access automatically.
EOF
gate_confirm "APPLY-NETWORK" "Type APPLY-NETWORK to rewrite /etc/network/interfaces and reboot" || exit 1
countdown_abort 12 "Rebooting in" || { warn "aborted by operator"; exit 1; }

# ---- apply ----------------------------------------------------------------
say "Writing /etc/network/interfaces"
backup_file /etc/network/interfaces "pre-stage2"
atomic_write /etc/network/interfaces <<EOF
# /etc/network/interfaces -- Proxmox VE bridge layout
# Generated by proxmox-dietpi-rpi4 v$PVE_RPI_VERSION on $(date -Is)
# Original DietPi configuration backed up in $WORKDIR/backup/

auto lo
iface lo inet loopback

# Physical NIC: no IP of its own, enslaved to the bridge
auto $NIC
iface $NIC inet manual

# Proxmox management bridge
auto $BRIDGE
iface $BRIDGE inet static
        address $PI_IP/$PI_CIDR
        gateway $PI_GATEWAY
        dns-nameservers $PI_DNS
        bridge-ports $NIC
        bridge-stp off
        bridge-fd 0
EOF
ok "wrote $BRIDGE config"

say "Retiring DietPi's drop-in"
mkdir -p "$WORKDIR/disabled"
if [ -f /etc/network/interfaces.d/eth0.conf ]; then
  mv /etc/network/interfaces.d/eth0.conf "$WORKDIR/disabled/eth0.conf"
  ok "moved eth0.conf aside"
else
  step "no eth0.conf drop-in"
fi
rm -f /etc/network/interfaces.d/* 2>/dev/null || true

say "Arming the rollback guard"
sed "s|__GATEWAY__|$PI_GATEWAY|g" "$HERE/net-guard.sh" > "$WORKDIR/net-guard.sh"
install -m 755 "$WORKDIR/net-guard.sh" /usr/local/sbin/net-guard.sh
atomic_write /etc/systemd/system/net-guard.service <<'UNIT'
[Unit]
Description=Network rollback guard (reverts a broken bridge config once)
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
ExecStart=/usr/local/sbin/net-guard.sh
TimeoutStartSec=300

[Install]
WantedBy=multi-user.target
UNIT
systemctl daemon-reload
systemctl enable net-guard.service >/dev/null 2>&1
rm -f /var/lib/.net-guard-ran

# ---- gate 3 (pre-reboot safety proof) -------------------------------------
gate_triple "stage 2 (pre-reboot)" \
  "config has the loopback stanza::grep -q '^auto lo' /etc/network/interfaces" \
  "NIC set to manual (no IP)::grep -q \"iface $NIC inet manual\" /etc/network/interfaces" \
  "bridge stanza present::grep -q \"iface $BRIDGE inet static\" /etc/network/interfaces" \
  "bridge enslaved to NIC::grep -q \"bridge-ports $NIC\" /etc/network/interfaces" \
  "address and gateway set::grep -q \"address $PI_IP/$PI_CIDR\" /etc/network/interfaces && grep -q \"gateway $PI_GATEWAY\" /etc/network/interfaces" \
  "rollback guard is enabled::systemctl is-enabled --quiet net-guard.service" \
  "rollback backup is intact::test -f $WORKDIR/backup/interfaces" \
  "guard knows the gateway::grep -q \"GATEWAY=$PI_GATEWAY\" /usr/local/sbin/net-guard.sh" \
  || die "pre-reboot verification failed — NOT rebooting. Fix the above and re-run."

state_set 3
say "Rebooting"
sync
sleep 2
systemctl reboot
